using System.Buffers.Binary;
using System.IO.MemoryMappedFiles;
using System.Net;
using System.Net.Sockets;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace CrystalCast.Video;

internal interface IWebKitGtkHostListener
{
    void OnHostStatus(string status);
    void OnHostLog(string message);
    void OnHostFailed(string reason, string details);
    void OnHostGraphics(string browserTexture, string outputTexture);
    void OnHostFrame(VideoFrame frame, double extractMilliseconds);
    void OnPageLoading();
    void OnPageMessage(string json);
    void OnControlsVisibilityChanged(bool visible);
    void OnHostWindow(string mode, string detail);
    void OnHostHealth(WebKitGtkHostHealth health);
}

internal sealed record WebKitGtkHostOptions(
    string HelperPath,
    string LauncherPath,
    string LogPath,
    int Width,
    int Height,
    float FramesPerSecond);

/// <summary>
/// One native WebKitGTK helper process and its loopback control connection.
/// Frames arrive in three leased BGRA slots of a shared file; each is copied and acknowledged.
/// </summary>
internal sealed class WebKitGtkHostSession : IDisposable
{
    public const int Protocol = 1;
    public const string HelperFileName = "crystalcast-webkit-host";
    public const string LauncherFileName = "crystalcast-webkit-host.sh";
    private const int Slots = 3;
    private const int MaximumMessageBytes = 1024 * 1024;
    private static readonly TimeSpan ConnectTimeout = TimeSpan.FromSeconds(30);

    private readonly WebKitGtkHostOptions options;
    private readonly IWebKitGtkHostListener listener;
    private readonly CancellationTokenSource cancellation = new();
    private readonly object writeLock = new();
    private readonly List<byte[]> pendingMessages = [];
    private readonly string token = Convert.ToHexString(RandomNumberGenerator.GetBytes(32)).ToLowerInvariant();
    private NetworkStream? stream;
    private TcpClient? client;
    private int disposed;
    private volatile bool failed;
    private string logPath;
    private string? stagingDirectory;

    public WebKitGtkHostSession(WebKitGtkHostOptions options, IWebKitGtkHostListener listener)
    {
        this.options = options;
        this.listener = listener;
        logPath = options.LogPath;
    }

    public string RuntimeDescription { get; private set; } = "not connected";

    public void Start()
    {
        _ = Task.Factory.StartNew(
            () => RunAsync(cancellation.Token),
            cancellation.Token,
            TaskCreationOptions.LongRunning,
            TaskScheduler.Default).Unwrap();
    }

    public void LoadPage(string url, string html) => Send(new { type = "load", url, html });

    public void PostToPage(string json)
    {
        JsonDocument document;
        try
        {
            document = JsonDocument.Parse(json);
        }
        catch (JsonException)
        {
            return; // Player messages are generated by the plugin; never fail a caller over one.
        }

        using (document)
            Send(new { type = "post", message = document.RootElement });
    }

    public void SetCaptureEnabled(bool enabled) => Send(new { type = "capture", enabled });

    public void SetMuted(bool muted) => Send(new { type = "muted", value = muted });

    public void SetFramesPerSecond(float fps) => Send(new { type = "fps", value = fps });

    public void SetControlsVisible(bool visible) => Send(new { type = "controls", visible });

    public void Dispose()
    {
        if (Interlocked.Exchange(ref disposed, 1) != 0)
            return;

        try
        {
            Send(new { type = "shutdown" });
        }
        catch
        {
            // Closing the connection also stops the helper.
        }

        cancellation.Cancel();
        lock (writeLock)
        {
            stream?.Dispose();
            client?.Dispose();
            stream = null;
            client = null;
        }

        // Keep a staged copy after a failure so its log can be read; Linux lets a running
        // program's file be deleted, so a clean shutdown removes it right away.
        if (!failed && stagingDirectory != null)
        {
            try
            {
                Directory.Delete(stagingDirectory, recursive: true);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
            }
        }
    }

    internal static byte[] Frame(object message)
    {
        var json = JsonSerializer.SerializeToUtf8Bytes(message);
        var framed = new byte[json.Length + 4];
        BinaryPrimitives.WriteUInt32LittleEndian(framed, (uint)json.Length);
        json.CopyTo(framed, 4);
        return framed;
    }

    private void Send(object message)
    {
        byte[] framed;
        try
        {
            framed = Frame(message);
        }
        catch (Exception)
        {
            return;
        }

        lock (writeLock)
        {
            if (Volatile.Read(ref disposed) != 0 && stream == null)
                return;

            if (stream == null)
            {
                pendingMessages.Add(framed);
                return;
            }

            try
            {
                stream.Write(framed);
            }
            catch (Exception)
            {
                // Called from game and UI threads: never throw. The read loop reports a lost connection.
            }
        }
    }

    private async Task RunAsync(CancellationToken cancellationToken)
    {
        var listenerSocket = new TcpListener(IPAddress.Loopback, 0);
        MemoryMappedFile? mappedFile = null;
        MemoryMappedViewAccessor? view = null;
        try
        {
            listenerSocket.Start(1);
            var port = ((IPEndPoint)listenerSocket.LocalEndpoint).Port;
            TryDeleteStaleLog();
            StartHelper(port);
            listener.OnHostLog($"started native WebKitGTK helper {options.HelperPath}; log {logPath}");
            listener.OnHostStatus("starting native WebKitGTK browser");

            TcpClient accepted;
            using (var timeout = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken))
            {
                timeout.CancelAfter(ConnectTimeout);
                var accept = listenerSocket.AcceptTcpClientAsync(timeout.Token).AsTask();
                try
                {
                    // launch.sh writes an exit line when the helper stops, so a failed
                    // start (for example a missing library) is reported immediately.
                    while (!accept.IsCompleted)
                    {
                        await Task.WhenAny(accept, Task.Delay(500, timeout.Token));
                        if (!accept.IsCompleted && HelperExitWasLogged())
                        {
                            timeout.Cancel();
                            throw new WebKitGtkHostException("the native browser exited during startup", helperEnded: true);
                        }
                    }

                    accepted = await accept;
                }
                catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
                {
                    throw new WebKitGtkHostException("the native browser did not start within 30 seconds", helperEnded: true);
                }
                finally
                {
                    _ = accept.ContinueWith(task => task.Exception, TaskScheduler.Default);
                }
            }

            listenerSocket.Stop();
            accepted.NoDelay = true;
            var connection = accepted.GetStream();
            using var hello = await ReadMessageAsync(connection, cancellationToken)
                ?? throw new WebKitGtkHostException("the native browser closed before connecting", helperEnded: true);
            ValidateHello(hello.RootElement);

            lock (writeLock)
            {
                if (Volatile.Read(ref disposed) != 0)
                {
                    accepted.Dispose();
                    return;
                }

                client = accepted;
                stream = connection;
                foreach (var message in pendingMessages)
                    stream.Write(message);
                pendingMessages.Clear();
            }

            var frameBytes = checked(options.Width * options.Height * 4);
            while (!cancellationToken.IsCancellationRequested)
            {
                using var document = await ReadMessageAsync(connection, cancellationToken);
                if (document == null)
                    throw new WebKitGtkHostException("the native browser stopped unexpectedly", helperEnded: true);

                var root = document.RootElement;
                switch (GetString(root, "type"))
                {
                    case "ready":
                        (mappedFile, view) = OpenMapping(root, frameBytes);
                        Send(new { type = "mapped" });
                        RuntimeDescription = $"{RuntimeDescription}; {Bounded(GetString(root, "renderer"))} on {Bounded(GetString(root, "display"))}";
                        listener.OnHostLog($"native WebKitGTK browser running: {RuntimeDescription}, {options.Width}x{options.Height}");
                        listener.OnHostStatus("native WebKitGTK browser running");
                        break;
                    case "frame":
                        if (view == null)
                            throw new WebKitGtkHostException("frame received before the shared frame file was ready");
                        DeliverFrame(root, view, frameBytes);
                        break;
                    case "page":
                        listener.OnPageMessage(GetString(root, "data"));
                        break;
                    case "loading":
                        listener.OnPageLoading();
                        break;
                    case "status":
                        listener.OnHostStatus(Bounded(GetString(root, "message")));
                        break;
                    case "graphics":
                        listener.OnHostGraphics(Bounded(GetString(root, "source")), Bounded(GetString(root, "output")));
                        break;
                    case "window":
                        listener.OnHostWindow(Bounded(GetString(root, "mode")), Bounded(GetString(root, "detail")));
                        break;
                    case "health":
                        listener.OnHostHealth(new WebKitGtkHostHealth(
                            GetInt64(root, "invalidations"),
                            GetInt64(root, "frames"),
                            GetInt64(root, "busy"),
                            GetBool(root, "mapped"),
                            GetBool(root, "minimized"),
                            GetBool(root, "suspended"),
                            GetBool(root, "capture"),
                            GetBool(root, "page")));
                        break;
                    case "controls":
                        listener.OnControlsVisibilityChanged(root.TryGetProperty("visible", out var visible) && visible.ValueKind == JsonValueKind.True);
                        break;
                    case "fatal":
                        throw new WebKitGtkHostException(Bounded(GetString(root, "message")));
                }
            }
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
        }
        catch (Exception ex) when (Volatile.Read(ref disposed) == 0)
        {
            ReportFailure(ex);
        }
        catch
        {
            // Errors while shutting down are expected.
        }
        finally
        {
            listenerSocket.Stop();
            lock (writeLock)
            {
                stream?.Dispose();
                client?.Dispose();
                stream = null;
                client = null;
            }

            view?.Dispose();
            mappedFile?.Dispose();
        }
    }

    private void StartHelper(int port)
    {
        var (helper, launcher, log) = ResolveUnixPaths();
        var fps = (int)Math.Round(Math.Clamp(options.FramesPerSecond, 1.0f, 120.0f));
        WineHostInterop.StartUnixProcess(
            "/bin/sh",
            [launcher, helper, "--width", options.Width.ToString(), "--height", options.Height.ToString(), "--fps", fps.ToString()],
            new Dictionary<string, string>
            {
                ["CRYSTALCAST_HOST_PORT"] = port.ToString(),
                ["CRYSTALCAST_HOST_TOKEN"] = token,
                ["CRYSTALCAST_HOST_LOG"] = log,
            });
    }

    /// <summary>
    /// Linux paths for the helper, its launcher and its log. When Wine hides its path
    /// functions (some Proton builds) and the plugin is not on the Z: drive, the two files
    /// are copied into a new private folder under XDG_RUNTIME_DIR (or /tmp) instead.
    /// </summary>
    private (string Helper, string Launcher, string Log) ResolveUnixPaths()
    {
        var helper = WineHostInterop.ToUnixPath(options.HelperPath);
        var launcher = WineHostInterop.ToUnixPath(options.LauncherPath);
        var log = WineHostInterop.ToUnixPath(logPath);
        if (helper != null && launcher != null && log != null)
            return (helper, launcher, log);

        var runtimeDirectory = Environment.GetEnvironmentVariable("XDG_RUNTIME_DIR");
        var baseDirectory = !string.IsNullOrEmpty(runtimeDirectory) && runtimeDirectory.StartsWith('/') && !runtimeDirectory.Contains('"')
            ? runtimeDirectory.TrimEnd('/')
            : "/tmp";
        var unixDirectory = $"{baseDirectory}/crystalcast-webkit-{Guid.NewGuid():N}";
        var windowsDirectory = WineHostInterop.ToWindowsPath(unixDirectory)
            ?? throw new WebKitGtkHostException(
                "Wine hides its path functions and has no Z: drive for the Linux root folder, so the Linux helper cannot be started");

        Directory.CreateDirectory(windowsDirectory);
        stagingDirectory = windowsDirectory;
        File.Copy(options.HelperPath, Path.Combine(windowsDirectory, HelperFileName));
        File.Copy(options.LauncherPath, Path.Combine(windowsDirectory, LauncherFileName));
        logPath = Path.Combine(windowsDirectory, "host.log");
        listener.OnHostLog($"Wine path functions are hidden; started the helper from a copy in {unixDirectory}");
        return (
            $"{unixDirectory}/{HelperFileName}",
            $"{unixDirectory}/{LauncherFileName}",
            $"{unixDirectory}/host.log");
    }

    private void ValidateHello(JsonElement hello)
    {
        var presented = Encoding.ASCII.GetBytes(GetString(hello, "token"));
        if (GetString(hello, "type") != "hello"
            || !CryptographicOperations.FixedTimeEquals(presented, Encoding.ASCII.GetBytes(token)))
        {
            throw new WebKitGtkHostException("rejected an unauthenticated native browser connection");
        }

        if (!hello.TryGetProperty("protocol", out var protocol) || !protocol.TryGetInt32(out var version) || version != Protocol)
            throw new WebKitGtkHostException("the native browser helper does not match this plugin version");

        RuntimeDescription = $"GTK {Bounded(GetString(hello, "gtk"))}, WebKitGTK {Bounded(GetString(hello, "webkit"))}";
    }

    private (MemoryMappedFile File, MemoryMappedViewAccessor View) OpenMapping(JsonElement ready, int frameBytes)
    {
        if (!ready.TryGetProperty("width", out var width) || width.GetInt32() != options.Width
            || !ready.TryGetProperty("height", out var height) || height.GetInt32() != options.Height
            || !ready.TryGetProperty("slots", out var slots) || slots.GetInt32() != Slots)
        {
            throw new WebKitGtkHostException("the native browser reported an unexpected frame layout");
        }

        var unixPath = GetString(ready, "mapping");
        var windowsPath = WineHostInterop.ToWindowsPath(unixPath)
            ?? throw new WebKitGtkHostException($"Wine cannot open the shared frame file {unixPath}");
        var file = new FileStream(windowsPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
        try
        {
            if (file.Length < (long)frameBytes * Slots)
                throw new WebKitGtkHostException("the shared frame file is too small");

            var mapped = MemoryMappedFile.CreateFromFile(file, null, (long)frameBytes * Slots, MemoryMappedFileAccess.Read, HandleInheritability.None, leaveOpen: false);
            return (mapped, mapped.CreateViewAccessor(0, (long)frameBytes * Slots, MemoryMappedFileAccess.Read));
        }
        catch
        {
            file.Dispose();
            throw;
        }
    }

    private unsafe void DeliverFrame(JsonElement root, MemoryMappedViewAccessor view, int frameBytes)
    {
        if (!root.TryGetProperty("seq", out var seqProperty) || !seqProperty.TryGetInt64(out var sequence)
            || !root.TryGetProperty("slot", out var slotProperty) || !slotProperty.TryGetInt32(out var slot)
            || slot < 0 || slot >= Slots)
        {
            throw new WebKitGtkHostException("the native browser sent an invalid frame notice");
        }

        var extractMilliseconds = root.TryGetProperty("extract_us", out var extract) && extract.TryGetDouble(out var us)
            ? us / 1000.0
            : 0.0;
        var frame = VideoFrame.Rent(options.Width, options.Height, sequence, DateTimeOffset.UtcNow.ToUnixTimeMilliseconds());
        byte* pointer = null;
        var handle = view.SafeMemoryMappedViewHandle;
        try
        {
            handle.AcquirePointer(ref pointer);
            new ReadOnlySpan<byte>(pointer + view.PointerOffset + ((long)slot * frameBytes), frameBytes)
                .CopyTo(frame.Pixels.AsSpan(0, frame.PixelLength));
        }
        catch
        {
            frame.Dispose();
            throw;
        }
        finally
        {
            if (pointer != null)
                handle.ReleasePointer();
        }

        Send(new { type = "ack", seq = sequence });
        listener.OnHostFrame(frame, extractMilliseconds);
    }

    private static async Task<JsonDocument?> ReadMessageAsync(Stream connection, CancellationToken cancellationToken)
    {
        var header = new byte[4];
        if (!await ReadExactlyOrEndAsync(connection, header, cancellationToken))
            return null;

        var length = BinaryPrimitives.ReadUInt32LittleEndian(header);
        if (length == 0 || length > MaximumMessageBytes)
            throw new WebKitGtkHostException("the native browser sent an oversized message");

        var body = new byte[length];
        if (!await ReadExactlyOrEndAsync(connection, body, cancellationToken))
            return null;

        return JsonDocument.Parse(body, new JsonDocumentOptions { MaxDepth = 16 });
    }

    private static async Task<bool> ReadExactlyOrEndAsync(Stream connection, byte[] buffer, CancellationToken cancellationToken)
    {
        var offset = 0;
        while (offset < buffer.Length)
        {
            int read;
            try
            {
                read = await connection.ReadAsync(buffer.AsMemory(offset), cancellationToken);
            }
            catch (IOException) when (!cancellationToken.IsCancellationRequested)
            {
                return false; // A reset connection means the helper process ended.
            }

            if (read == 0)
                return false;
            offset += read;
        }

        return true;
    }

    private void ReportFailure(Exception ex)
    {
        failed = true;
        string reason;
        var details = string.Empty;
        if (ex is WebKitGtkHostException hostException)
        {
            // The connection closes a moment before launch.sh records the exit code.
            for (var i = 0; hostException.HelperEnded && i < 10 && !HelperExitWasLogged(); i++)
                Thread.Sleep(100);

            var (logText, logWritten) = ReadLog();
            reason = hostException.HelperEnded
                ? $"{ex.Message}. {WebKitGtkFailureDiagnosis.Explain(logText, logWritten, IsInsideFlatpak(), IsInsideSteamRuntime())}"
                : ex.Message;
            details = logWritten
                ? $"Helper log {logPath} (last lines):{Environment.NewLine}{logText}"
                : $"No helper log was written at {logPath}.";
        }
        else
        {
            reason = $"internal error {ex.GetType().Name}: {ex.Message}";
            details = ex.ToString();
        }

        try
        {
            listener.OnHostFailed(reason, details);
        }
        catch
        {
            // A failing listener must not take down the background thread.
        }
    }

    private (string Text, bool Written) ReadLog()
    {
        try
        {
            if (!File.Exists(logPath))
                return (string.Empty, false);

            using var file = new FileStream(logPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
            const int MaximumBytes = 64 * 1024;
            if (file.Length > MaximumBytes)
                file.Seek(-MaximumBytes, SeekOrigin.End);
            using var reader = new StreamReader(file, Encoding.UTF8);
            var lines = reader.ReadToEnd()
                .Split('\n')
                .Select(line => line.TrimEnd('\r'))
                .Where(line => !string.IsNullOrWhiteSpace(line))
                .TakeLast(40)
                .Select(Bounded);
            return (string.Join(Environment.NewLine, lines), true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return ($"(could not read the helper log: {ex.Message})", true);
        }
    }

    private bool HelperExitWasLogged()
    {
        try
        {
            if (!File.Exists(logPath))
                return false;

            using var file = new FileStream(logPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
            if (file.Length > 4096)
                file.Seek(-4096, SeekOrigin.End);
            using var reader = new StreamReader(file, Encoding.UTF8);
            return reader.ReadToEnd().Contains("CRYSTALCAST_HOST_EXIT", StringComparison.Ordinal);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return false;
        }
    }

    private void TryDeleteStaleLog()
    {
        try
        {
            File.Delete(logPath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
        }
    }

    /// <summary>Proton runs games inside Steam's Linux Runtime (pressure-vessel) container.</summary>
    private static bool IsInsideSteamRuntime()
    {
        try
        {
            var marker = WineHostInterop.ToWindowsPath("/run/host/os-release");
            return (marker != null && File.Exists(marker))
                || !string.IsNullOrEmpty(Environment.GetEnvironmentVariable("PRESSURE_VESSEL_RUNTIME"));
        }
        catch
        {
            return false;
        }
    }

    private static bool IsInsideFlatpak()
    {
        try
        {
            var marker = WineHostInterop.ToWindowsPath("/.flatpak-info");
            return marker != null && File.Exists(marker);
        }
        catch
        {
            return false;
        }
    }

    private static string GetString(JsonElement element, string name) =>
        element.TryGetProperty(name, out var property) && property.ValueKind == JsonValueKind.String
            ? property.GetString() ?? string.Empty
            : string.Empty;

    private static long GetInt64(JsonElement element, string name) =>
        element.TryGetProperty(name, out var property) && property.TryGetInt64(out var value) ? value : 0;

    private static bool GetBool(JsonElement element, string name) =>
        element.TryGetProperty(name, out var property) && property.ValueKind == JsonValueKind.True;

    private static string Bounded(string value) => value.Length <= 300 ? value : value[..300];
}

internal sealed class WebKitGtkHostException(string message, bool helperEnded = false) : Exception(message)
{
    /// <summary>The helper never connected or its process ended; its log explains why.</summary>
    public bool HelperEnded { get; } = helperEnded;
}
